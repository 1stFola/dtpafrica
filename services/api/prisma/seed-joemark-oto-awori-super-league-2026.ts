export const JOEMARK_MATCH_GOALS: Record<
  string,
  { minute: number; side: "home" | "away"; scorer: string; ownGoal: boolean }[]
> = Object.fromEntries(
  MATCHES.filter((m) => m.goals.length).map((m) => [
    m.id,
    m.goals.map((g) => ({ minute: g.minute, side: g.side, scorer: g.scorer, ownGoal: g.ownGoal })),
  ])
);

/** Match id -> venue, for the same repair. Both read the array the seed writes. */
export const JOEMARK_MATCH_VENUES: Record<string, string> = Object.fromEntries(
  MATCHES.filter((m) => m.venue).map((m) => [m.id, m.venue as string])
);

export async function seedJoemarkOtoAworiSuperLeague2026(prisma: PrismaClient) {
  const formatConfig = {
    format: "double_round_robin",
    overview: DESCRIPTION,
    timezone: TIMEZONE,
    teams: 12,
    matches: 132,
    /* 131 of the 132 fixtures have been published so far. The one still to come
       is Young Fellas FA v Future Stars FC, which no batch has scheduled yet. */
    fixturesPublished: MATCHES.length,
    league: { homeAndAway: true },
    points: { win: 3, draw: 1, loss: 0 },
    tiebreakers: ["points", "goal_difference", "goals_for", "head_to_head"],
  };

  const fields = {
    name: COMP_NAME,
    season: "2026",
    type: "league",
    formatType: "STANDARD_LEAGUE",
    formatConfig: formatConfig as Prisma.InputJsonValue,
    country: "Nigeria",
    logoUrl: COMP_LOGO,
    description: DESCRIPTION,
    status: "active",
    isPublished: true,
  };

  const comp = await prisma.sbCompetition.upsert({
    where: { slug: COMP_SLUG },
    update: fields,
    create: { id: COMP_ID, slug: COMP_SLUG, ...fields },
  });

  const teamIds: Record<string, string> = {};
  for (const team of TEAMS) {
    const teamFields = {
      name: normalizeClubName(team.name),
      shortName: team.name,
      logoUrl: team.logoUrl,
      /* One league table, so no group key: the standings render as a single
         table rather than a set of groups. */
      groupKey: null,
    };
    const row = await prisma.sbTeam.upsert({
      where: { competitionId_slug: { competitionId: comp.id, slug: team.slug } },
      update: teamFields,
      create: { id: team.id, competitionId: comp.id, slug: team.slug, ...teamFields },
    });
    teamIds[team.slug] = row.id;
  }

  /* Squad entries carry no playerId on purpose — see the note at the top of this
     file. Keyed by team + display name so a re-run updates rather than duplicates. */
  for (const entry of SQUADS) {
    const teamId = teamIds[entry.teamSlug];
    if (!teamId) continue;
    const existing = await prisma.sbTeamSquad.findFirst({
      where: { teamId, displayName: entry.name },
      select: { id: true },
    });
    const squadFields = {
      teamId,
      displayName: entry.name,
      shirtNumber: entry.shirtNumber,
      position: entry.position,
    };
    if (existing) {
      await prisma.sbTeamSquad.update({ where: { id: existing.id }, data: squadFields });
    } else {
      await prisma.sbTeamSquad.create({ data: squadFields });
    }
  }

  const slugFor = await createSeedMatchSlugAllocator(prisma, MATCHES.map((m) => m.id));
  let seeded = 0;
  let preserved = 0;
  for (const match of MATCHES) {
    /* Never overwrite a match the admin has already worked on: once it has
       kicked off, finished or had events recorded, it belongs to whoever
       recorded it. */
    if (await shouldPreserveSbMatch(prisma, match.id)) {
      preserved += 1;
      continue;
    }
    const shared = {
      slug: slugFor(match.id, match.homeSlug, match.awaySlug),
      homeTeamId: teamIds[match.homeSlug],
      awayTeamId: teamIds[match.awaySlug],
      status: match.status,
      homeScore: match.homeScore,
      awayScore: match.awayScore,
      minute: null,
      kickoffAt: new Date(match.kickoffAt),
      venue: match.venue || null,
      matchComment: match.walkover ? "Awarded as a walkover." : null,
      // `stats` is a nullable Json column; Prisma rejects a bare `null` here and
      // requires DbNull to write a SQL NULL.
      stats: Prisma.DbNull,
      isPublished: true,
      meta: { timezone: TIMEZONE, walkover: match.walkover } as Prisma.InputJsonValue,
    };
    await prisma.sbMatch.upsert({
      where: { id: match.id },
      update: shared,
      create: { id: match.id, competitionId: comp.id, ...shared },
    });

    /* Goals are replaced wholesale for this match rather than merged: the source
       sheet is the authority, and a partial merge would leave a corrected
       scoreline sitting next to the goals it replaced. */
    if (match.goals.length) {
      await prisma.sbMatchEvent.deleteMany({ where: { matchId: match.id } });
      for (const goal of match.goals) {
        await prisma.sbMatchEvent.create({
          data: {
            matchId: match.id,
            teamId: teamIds[goal.side === "home" ? match.homeSlug : match.awaySlug],
            type: goal.ownGoal ? "own_goal" : "goal",
            minute: goal.minute,
            playerLabel: goal.scorer,
            /* One goal in the sheet has a scorer but no minute. It is recorded at
               minute 0 with the reason stated, rather than dropped (which would
               leave the events disagreeing with the scoreline) or given an
               invented minute. */
            detail: goal.minuteKnown ? null : "Minute not recorded in the source sheet",
          },
        });
      }
    }
    seeded += 1;
  }

  const [teamCount, matchCount, squadCount, goalCount, venueCount, logoCount] = await Promise.all([
    prisma.sbTeam.count({ where: { competitionId: comp.id } }),
    prisma.sbMatch.count({ where: { competitionId: comp.id } }),
    prisma.sbTeamSquad.count({ where: { team: { competitionId: comp.id } } }),
    prisma.sbMatchEvent.count({ where: { match: { competitionId: comp.id } } }),
    /* Counted because the first version of this seed shipped 101 null venues: the
       parser never captured the column and nothing checked. */
    prisma.sbMatch.count({ where: { competitionId: comp.id, venue: { not: null } } }),
    prisma.sbTeam.count({ where: { competitionId: comp.id, logoUrl: { not: null } } }),
  ]);
  console.log(
    `Seeded ${COMP_NAME}: ${teamCount} teams (expected 12), ${matchCount} matches ` +
      `(expected ${MATCHES.length}), ${squadCount} squad entries (expected ${SQUADS.length}), ` +
      `${goalCount} goals (expected 235), ${venueCount} venues (expected ${MATCHES.length}), ` +
      `${logoCount} crests (expected ${TEAMS.length}). ${seeded} written, ${preserved} preserved.`
  );
  return { comp, teamCount, matchCount, squadCount, goalCount };
}
