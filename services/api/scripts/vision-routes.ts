/**
 * Every Vision route, read from the controllers, as the table in
 * docs/vision/07-API-CONTRACTS.md § "Every route, as built".
 *
 *   pnpm --filter @dtp/api vision:routes          # print the table
 *   pnpm --filter @dtp/api vision:routes --write  # put it in the doc
 *
 * Doc 07 was written before the code and edited by hand as routes landed. By
 * the QA of Phases 1 to 6 it listed twenty routes that did not exist and left
 * out fifty-three that did (docs/vision/50, appendices A and F). The table is
 * now generated, and `vision-routes.spec.ts` fails when the doc and the
 * controllers disagree, so the next route cannot be forgotten.
 *
 * It reads the decorators as text. That is enough because every Vision
 * controller writes them the same way: `@Controller("…")` on the class,
 * `@Get("…")` and the rest on the method, `@RequirePermissions("…")` beside it.
 */
import { readFileSync, readdirSync, statSync, writeFileSync } from "node:fs";
import { join, relative, resolve } from "node:path";

export type Route = { method: string; path: string; access: string; file: string };

/** How a route is guarded when it is not by an admin session and a permission. */
const GUARD_WORDS: Record<string, string> = {
  VisionWorkerGuard: "worker token",
  VisionWorkerBootstrapGuard: "bootstrap token",
  PartnerUploadGuard: "upload-grant token",
};

const VERB = /@(Get|Post|Patch|Put|Delete)\(\s*(?:"([^"]*)")?\s*\)/g;

export function routesIn(text: string, file: string): Route[] {
  /* A checkout on Windows has CRLF. Left as it was, the end of the previous method was not
     found and every route was given the permission of the one before it. */
  const source = text.replace(/\r\n/g, "\n");
  const out: Route[] = [];
  const classes = [...source.matchAll(/@Controller\(\s*"([^"]*)"\s*\)/g)];
  classes.forEach((controller, index) => {
    const start = controller.index!;
    const end = classes[index + 1]?.index ?? source.length;
    const body = source.slice(start, end);
    // Decorators between `@Controller` and `export class` guard every method.
    const head = body.slice(0, body.indexOf("export class"));
    const classGuard = Object.keys(GUARD_WORDS).find((g) => head.includes(g)) ?? null;
    const verbs = [...body.matchAll(VERB)];
    verbs.forEach((verb, v) => {
      // The method's other decorators sit between this verb and the method's signature;
      // a guard or a permission may also be written above the verb, after the previous method's body.
      const before = body.slice(verbs[v - 1] ? verbs[v - 1]!.index! + verbs[v - 1]![0].length : 0, verb.index!);
      const above = before.slice(before.lastIndexOf("}\n") + 1);
      const after = body.slice(verb.index! + verb[0].length);
      const beside = after.slice(0, after.search(/\n\s*(async\s+)?[A-Za-z_]+\s*\(/));
      const decorators = `${above}\n${beside}`;
      const permission = /@RequirePermissions\(\s*"([^"]+)"/.exec(decorators)?.[1];
      const methodGuard = Object.keys(GUARD_WORDS).find((g) => decorators.includes(g)) ?? null;
      const guard = methodGuard ?? classGuard;
      const path = `/${[controller[1]!, verb[2] ?? ""].map((p) => p.replace(/^\/|\/$/g, "")).filter(Boolean).join("/")}`;
      out.push({ method: verb[1]!.toUpperCase(), path, access: permission ?? (guard ? GUARD_WORDS[guard]! : ""), file });
    });
  });
  return out;
}

function controllersUnder(dir: string): string[] {
  return readdirSync(dir).flatMap((name) => {
    const full = join(dir, name);
    if (statSync(full).isDirectory()) return controllersUnder(full);
    return name.endsWith(".controller.ts") ? [full] : [];
  });
}

const VISION_DIR = resolve(__dirname, "../src/vision");
export const DOC_PATH = resolve(__dirname, "../../../docs/vision/07-API-CONTRACTS.md");
export const BEGIN = "<!-- routes:begin (generated by `pnpm --filter @dtp/api vision:routes --write`; do not edit by hand) -->";
export const END = "<!-- routes:end -->";

export function scanRoutes(dir = VISION_DIR): Route[] {
  return controllersUnder(dir)
    .flatMap((file) => routesIn(readFileSync(file, "utf8"), relative(dir, file).replace(/\\/g, "/")))
    .sort((a, b) => a.path.localeCompare(b.path) || a.method.localeCompare(b.method));
}

export function renderTable(routes: readonly Route[]): string {
  const rows = routes.map((r) => `| \`${r.method}\` | \`${r.path}\` | ${r.access.startsWith("vision.") ? `\`${r.access}\`` : r.access} | \`${r.file}\` |`);
  return ["| Method | Path | Access | Controller |", "|---|---|---|---|", ...rows].join("\n");
}

/** The doc with the generated block replaced; throws when the markers are missing. */
export function withTable(doc: string, table: string): string {
  const a = doc.indexOf(BEGIN);
  const b = doc.indexOf(END);
  if (a === -1 || b === -1 || b < a) throw new Error("docs/vision/07-API-CONTRACTS.md has no routes:begin / routes:end markers");
  return `${doc.slice(0, a + BEGIN.length)}\n${table}\n${doc.slice(b)}`;
}

/** The routes a hand-written table in the doc names: `| \`GET\` | \`/vision/…\` …`, with the line they are on. */
export function routesNamedIn(doc: string): { method: string; path: string; line: number; text: string }[] {
  return doc.split("\n").flatMap((text, i) => {
    const m = /^\|\s*`(GET|POST|PATCH|PUT|DELETE)`\s*\|\s*`([^`\s?]+)/.exec(text);
    return m ? [{ method: m[1]!, path: m[2]!, line: i + 1, text }] : [];
  });
}

/** `:id` and `:assetId` are the same route. */
export const shape = (path: string) => path.replace(/:[A-Za-z]+/g, ":x");

if (require.main === module) {
  const table = renderTable(scanRoutes());
  if (process.argv.includes("--write")) {
    writeFileSync(DOC_PATH, withTable(readFileSync(DOC_PATH, "utf8").replace(/\r\n/g, "\n"), table));
    console.log(`Wrote ${scanRoutes().length} routes into ${relative(process.cwd(), DOC_PATH)}`);
  } else {
    console.log(table);
  }
}
